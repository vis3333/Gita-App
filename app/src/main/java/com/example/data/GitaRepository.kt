    fun getDailyVerse(dayOfYear: Int = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)): GitaVerse {
        val index = (dayOfYear - 1).coerceAtLeast(0) % verses.size
        return verses[index]
    }

    fun getVerseById(id: String): GitaVerse? {
        return verses.find { it.id == id } ?: verses.firstOrNull()
    }

    fun searchVerses(query: String, chapterFilter: Int? = null, tagFilter: String? = null): List<GitaVerse> {
        val cleanQuery = query.trim().lowercase()
        return verses.filter { verse ->
            val matchesChapter = chapterFilter == null || verse.chapter == chapterFilter
            val matchesTag = tagFilter == null || verse.tags.any { it.equals(tagFilter, ignoreCase = true) }
            val matchesQuery = cleanQuery.isEmpty() ||
                    verse.verseReference.lowercase().contains(cleanQuery) ||
                    verse.englishTranslation.lowercase().contains(cleanQuery) ||
                    verse.hindiTranslation.lowercase().contains(cleanQuery) ||
                    verse.transliteration.lowercase().contains(cleanQuery) ||
                    verse.coreTeaching.lowercase().contains(cleanQuery) ||
                    verse.commentary.lowercase().contains(cleanQuery) ||
                    verse.tags.any { it.lowercase().contains(cleanQuery) }

            matchesChapter && matchesTag && matchesQuery
        }
    }

